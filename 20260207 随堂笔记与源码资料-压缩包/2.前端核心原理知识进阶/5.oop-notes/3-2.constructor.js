  // /*
  // .########.##.....##.########.########.##....##.########...######.
  // .##........##...##.....##....##.......###...##.##.....##.##....##
  // .##.........##.##......##....##.......####..##.##.....##.##......
  // .######......###.......##....######...##.##.##.##.....##..######.
  // .##.........##.##......##....##.......##..####.##.....##.......##
  // .##........##...##.....##....##.......##...###.##.....##.##....##
