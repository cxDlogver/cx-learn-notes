// class A {} // A类
// class B extends A {} // B类
// 1. 原型链继承

function A() {
  this.name = "heyi";
  this.hobby = [];
}

A.prototype.say = function () {
  console.log(this.name);
};

// 实现这个 B，能继承自 A
function B() {}
// /*
// .########.##.....##.########.########.##....##.########...######.
// .##........##...##.....##....##.......###...##.##.....##.##....##
// .##.........##.##......##....##.......####..##.##.....##.##......
// .######......###.......##....######...##.##.##.##.....##..######.
// .##.........##.##......##....##.......##..####.##.....##.......##
// .##........##...##.....##....##.......##...###.##.....##.##....##
// .########.##.....##....##....########.##....##.########...######.
// */
// B.prototype.__proto__ = A.prototype;
B.prototype = new A();
// /*
// .########.##.....##.########.########.##....##.########...######.
// .##........##...##.....##....##.......###...##.##.....##.##....##
// .##.........##.##......##....##.......####..##.##.....##.##......
// .######......###.......##....######...##.##.##.##.....##..######.
// .##.........##.##......##....##.......##..####.##.....##.......##
// .##........##...##.....##....##.......##...###.##.....##.##....##
// .########.##.....##....##....########.##....##.########...######.
// */

const a = new A();

a.say();

const b = new B();

b.say();
console.log("b.__proto__ === B.prototype", b.__proto__ === B.prototype);
console.log(
  "B.prototype.__proto__ === A.prototype",
  B.prototype.__proto__ === A.prototype,
);

// 大毛病
// 1. 如果父类存在引用数据类型，那么在子类中会共享数据，因为使用的是同一个父类初始化的实例
// 2. 没办法给父类构造器传参
const b2 = new B();

a.name = "haha";
a.hobby.push(1);
b.hobby.push("1")

console.log(b.name, b2.name, a.name);
console.log(b.hobby, b2.hobby, a.hobby);
